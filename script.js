function renderTicker(ticker) {
    Debug.subgroup('{ 🖼 RENDER TICKER SYMBOL }');
    const _s = App.settings;
    const _L = App.data.localStorage;
    const _I = App.elements.info;
    const _S = App.elements.sys;
    const _U = App.elements.ui;

    const stock = _L.currentPortfolio[ticker];
    if (!stock) throw new Error("⛔ Ticker not found: " + ticker);
    _L.currentTicker = ticker;

    // Update user
    let m = `Rendering new ticker symbol data: ${ticker.toUpper()}...`;
    message(m, 'i');
    wait(1000);

    // handle isDefault state for new ticker
    const newModifiedState = getConfig().modifiedState;
    if (_s.isDefault === null) {
        // first load
        _s.isDefault = stock.defaults !== false;
    } else if (!_s.isDefault && newModifiedState === 'null') {
        // was on modified, but new ticker's modified is disabled — force default
        _s.isDefault = true;
    }

    // company and financials shortcuts
    const C = stock.COMPANY    || {};
    const F = stock.FINANCIALS || {};

    // price and change
    const price     = parseFloat(stock.price) || 0;
    const changeRaw = F.change && F.change !== null ? F.change : 0;

    // get active config via getConfig()
    const { active } = getConfig();
    const discPct    = active.BLOCKAGE_DISCOUNT;
    const feePct     = active.BROKERAGE_FEE;
    const feePctSell = active.BROKERAGE_FEE_SELL;
    const sellMinPct = active.SELL_MIN;
    const sellMaxPct = active.SELL_MAX;

    // price calculations
    const bid     = fmsRoundPrice(price * (1 - discPct));
    const sellMin = fmsRoundPrice(bid *   (1 + sellMinPct));
    const sellMax = fmsRoundPrice(bid *   (1 + sellMaxPct));

    // block calculationsl
    const feePctMult     = 1 + feePct;
    const blockMinRaw    = _s.DEFAULT_MINIMUM_THRESHOLD / (bid * feePctMult);
    const blockMin       = Math.max(1, fmsRoundShares(blockMinRaw, bid, feePct));
    const blockMinDouble = blockMin * 2;
    const blockMaxHalf   = blockMin * 5;
    const blockMax       = blockMin * 10;
    const blocks         = [blockMax, blockMaxHalf, blockMinDouble, blockMin];

    // market update percentages
    const labelBidPct = ((price - bid)   / bid) * 100;
    const labelMinPct = ((sellMin - bid) / bid) * 100;
    const labelMaxPct = ((sellMax - bid) / bid) * 100;

    // company name
    const rawName       = C.name;
    const processedName = applyRegexReplacements(rawName);

    // populate header
    _U.txtDevCompany.textContent = processedName || ticker;
    _S.date.textContent          = formatDate(new Date());

    // populate market update cards
    updateMarketCards(price, bid, sellMin, sellMax, labelBidPct, labelMinPct, labelMaxPct);

    // change badge
    const change = formatPercent(changeRaw, false, 0.01);
    if (changeRaw) {
        _I.pctChange.textContent = change;
        _I.pctChange.className   = "text-badge " + (changeRaw < 0 ? "down" : "up");
    } else {
        _I.pctChange.textContent = "";
        _I.pctChange.className   = "text-badge";
    }

    // description
    const formattedDesc = formatDescription();
    const processedDesc = applyRegexReplacements(formattedDesc);
    const description   = processedDesc.d;
    const summary       = processedDesc.s;

    // populate information section
    _I.infCompany.textContent     = processedName || "";
    _I.infTicker.textContent      = C.ticker      || "";
    _I.infExchange.textContent    = C.exchange    || "";
    _I.infCountry.textContent     = C.country     || "";
    _I.infIndustry.textContent    = C.industry    || "";
    _I.infSector.textContent      = C.sector      || "";
    _I.infYear.textContent        = C.year        || "";
    _I.marketCap.textContent      = formatCurrency(F.marketCap, true) || "";
    _I.infDescription.textContent = (App.state.fullDesc === "show" ? description : summary) || "";
    _I.wkLow.textContent          = formatCurrency(F.weekLow)    || "";
    _I.wkHigh.textContent         = formatCurrency(F.weekHigh)   || "";
    _I.yrTarget.textContent       = formatCurrency(F.yearTarget) || "";

    // show or hide cards based on available data
    // toggleCard('week-low', F.weekLow);
    // toggleCard('week-high', F.weekHigh);
    toggleCard(_I.wkLow, F.weekLow);
    toggleCard(_I.wkHigh, F.weekHigh);

    // website link
    const url        = C.website || "";
    const link       = _U.infWebsite;
    link.href        = url;
    link.textContent = formatUrl(url) || "";

    // adjust select menu width, render settings and price tables, render news feed and sync price modd
    adjustWidth(_U.selDevCompany);
    renderTableSettings();
    renderTablePrice(blocks, bid, feePct, feePctSell, sellMin, sellMax);
    renderNews();
    syncModeUI()

    m = `Company information loaded for ticker symbol ${ticker}.`;
    message(m, 's');
    wait(1000);
    Debug.log('🏷', m);
    Debug.end();
}

