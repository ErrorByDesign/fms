function renderTablePrice(blocks, bid, feePct, feePctSell, sellMin, sellMax) {
    Debug.subgroup('{ 💰 RENDER PRICE TABLE }');

    const _T = App.elements.table;
    const _s = App.state;

    _T.tBodyPrice.innerHTML = "";

    const feeBuy  = 1 + feePct;
    const feeSell = 1 - feePctSell;

    blocks.forEach(b => {
        const cost    = b * bid * feeBuy;
        const comms   = cost - b * bid;
        const total   = cost;
        const grossL  = b * sellMin;
        const netL    = grossL * feeSell;
        const profitL = netL - total;
        const grossH  = b * sellMax;
        const netH    = grossH * feeSell;
        const profitH = netH - total;
        const tr      = document.createElement("tr");
        tr.classList.add('tr-body-price');
        tr.innerHTML =
            `<td class="tbl-col-price     anim-freeze-col-L">${b}</td>` +
            `<td class="tbl-col-price     tdp-cost">${formatCurrency(b * bid)}</td>` +
            `<td class="tbl-col-price     tdp-coms">${formatCurrency(comms)}</td>` +
            `<td class="tbl-col-price     tdp-totl">${formatCurrency(total)}</td>` +
            `<td class="tbl-col-price     tdp-sell" data-low="${formatCurrency(netL)}" data-high="${formatCurrency(netH)}">${_s.mode === 'low' ? formatCurrency(netL) : formatCurrency(netH)}</td>` +
            `<td class="tbl-col-price     anim-freeze-col-R ${_s.mode === 'low' ? 'anim-pmin' : 'anim-pmax'}" data-low="${formatCurrency(profitL)}" data-high="${formatCurrency(profitH)}">${_s.mode === 'low' ? formatCurrency(profitL) : formatCurrency(profitH)}</td>`;
        _T.tBodyPrice.appendChild(tr);
    });

    if (_s.frozenL === "frozen") {
        document.querySelectorAll(".anim-freeze-col-L").forEach(td => td.classList.add("frozen"));
    }
    if (_s.frozenR === "frozen") {
        document.querySelectorAll(".anim-freeze-col-R").forEach(td => td.classList.add("frozen"));
    }

    Debug.end();
}
