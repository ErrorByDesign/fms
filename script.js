async function loadData() {
    try {
        const _d = App.developer;
        const _L = App.data.localStorage;
        const _S = App.elements.sys;
        const _U = App.elements.ui;

        // Load regex replacement map FIRST
        await loadRegexReplaceMap();

        // If dev mode has been initialized, load from localStorage
        let portfolioJson, reportJson, settingsJson;
        if (_d.devModeInitialized) {
            const storedPortfolio = localStorage.getItem('fms-portfolio');
            const storedReport    = localStorage.getItem('fms-report');
            const storedSettings  = localStorage.getItem('fms-settings');
            
            if (storedPortfolio && storedSettings && storedReport) {
                portfolioJson = JSON.parse(storedPortfolio);
                reportJson    = JSON.parse(storedReport);
                settingsJson  = JSON.parse(storedSettings);
                Debug.log('💾 Loaded data from localStorage');
            } else {
                const [portfolioRes, reportRes, settingsRes] = await Promise.all([
                    fetch("./data/portfolio.json"),
                    fetch("./config/report-portfolio.json"),
                    fetch("./config/settings.json")
                ]);
                portfolioJson = await portfolioRes.json();
                reportJson    = await reportRes.json();
                settingsJson  = await settingsRes.json();

                Debug.log('🗄 Loaded data from JSON (localStorage fallback)');
            }
        } else {
            // First load: get from JSON
            const [portfolioRes, reportRes, settingsRes] = await Promise.all([
                fetch("./data/portfolio.json"),
                fetch("./config/report-portfolio.json"),
                fetch("./config/settings.json")
            ]);
            portfolioJson = await portfolioRes.json();
            reportJson    = await reportRes.json();
            settingsJson  = await settingsRes.json();

            Debug.log('📡 Loaded data from JSON (first load)');
        }
        _L.currentPortfolio = portfolioJson;
        _L.currentReport    = reportJson;
        _L.currentSettings  = settingsJson;

        // populate dropdown
        const tickers = Object.keys(portfolioJson).reverse();
        _U.selDevCompany.innerHTML = "";
        tickers.forEach(ticker => {
            const opt       = document.createElement("option");
            opt.value       = ticker;
            opt.textContent = ticker;
            _U.selDevCompany.appendChild(opt);
        });

        // render first ticker
        renderTicker(tickers[0]);

        Debug.log('📡 Data loaded');
    } catch (e) {
        const t = 'x';
        const m = e;
        message(m, t);
        
        Debug.error('⛔ ',e);
    }
}
