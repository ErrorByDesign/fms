    const type     = _L.currentPortfolio[_L.currentTicker].stockType;
    const defaults = _L.currentSettings[type].DEFAULT;
    const modified = _L.currentSettings[type].MODIFIED;

    const keys = [
        "BLOCKAGE_DISCOUNT",
        "BROKERAGE_FEE",
        "BROKERAGE_FEE_SELL",
        "SELL_MIN",
        "SELL_MAX"
    ];

    // determine which keys are effective
    const effectiveKeys = keys.filter(k => modified[k] !== null && modified[k] !== defaults[k]);

    // determine modifiedState
    let modifiedState;
    if (effectiveKeys.length === 0) modifiedState = "null";
    else if (effectiveKeys.length === keys.length) modifiedState = "full";
    else modifiedState = "mix";

    // build merged config — effective modified values, fallback to default
    const merged = {};
    keys.forEach(k => {
        merged[k] = effectiveKeys.includes(k) ? modified[k] : defaults[k];
    });

    // active config for calculations
    const active = _s.isDefault ? defaults : merged;

    // alternative — raw modified for display when modifiedState === 'null'
    const alternative = _s.isDefault ? modified : defaults;

    const config = {
        active,
        alternative,
        defaults,
        modified,
        modifiedState,
        effectiveKeys
    };
    Debug.subgroup('{ 🔧 RAW CONFIGURATION DATA }');
    Debug.subgroup('\n{ ACTIVE }');
