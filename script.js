function isMarketOpen() {
    let now       = new Date();
    let utcHour   = now.getUTCHours();
    let utcMinute = now.getUTCMinutes();
    let utcDay    = now.getUTCDay();

    // Weekend
    if (utcDay === 0 || utcDay === 6) {
        Debug.log('💤 Market closed for the weekend');
        return false;
    }

    let currentMinutes = utcHour * 60 + utcMinute;
    let startMinutes   = 14 * 60 + 15; // 14:15 UTC
    let endMinutes     = 20 * 60 + 45; // 20:45 UTC

    const marketOpen = currentMinutes >= startMinutes && currentMinutes <= endMinutes;

    Debug.log(`🏛 Market status: ${marketOpen === true ? "🕘 Open" : "🕔 Closed"}`);
    return marketOpen;
}
