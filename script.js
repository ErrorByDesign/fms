async function submitSearchPrice() {
    const _L = App.data.localStorage;
    const _U = App.elements.ui;

    const placeholder = _U.inpDevPrice.placeholder;
    const inpValue = _U.inpDevPrice.value.trim();

    let rawPrice  = null;
    let rawChange = null;
    
    try {
        if (!inpValue || inpValue === placeholder) {
            // Fetch from Alpha Vantage
            Debug.log(`📡 Fetching latest price for ${_L.currentTicker}...`);
            const quote = await fetchAlphaVantageQuote(_L.currentTicker);
            rawPrice    = quote.price;
            rawChange   = quote.change;
        } else {
            // Use manual input
            rawPrice = parseFloat(inpValue);
            if (isNaN(rawPrice)) {
                throw new Error('Invalid price');
            }
            const ticker = _L.currentTicker;
            const portfolioData = JSON.parse(localStorage.getItem("fms-portfolio"));
            let oldPrice = portfolioData[ticker].price;
            rawChange = ((rawPrice - oldPrice) / oldPrice) * 100;
        }

        // Update currentPortfolio in memory
        _L.currentPortfolio[_L.currentTicker].price = rawPrice;
        _L.currentPortfolio[_L.currentTicker].FINANCIALS.change = rawChange;

        // Update localStorage
        const portfolio = JSON.parse(localStorage.getItem('fms-portfolio') || '{}');
        if (portfolio[_L.currentTicker]) {
            portfolio[_L.currentTicker].price = rawPrice;
            portfolio[_L.currentTicker].FINANCIALS.change = rawChange;
            localStorage.setItem('fms-portfolio', JSON.stringify(portfolio));
        }

        // Recalculate and re-render
        renderTicker(_L.currentTicker);

        // Lock dev mode but keep price themed
        devopsPrimaryLock();

        console.log(`✅ Price updated to ${rawPrice}`);
    } catch (error) {
        const e = `❌ Price update failed: ${error.message}`;

        message(e, 'e');

        _U.inpDevPrice.placeholder = "";
        _U.inpDevPrice.focus();

        Debug.error('❌ Price update failed:', error.message);
    }
}

